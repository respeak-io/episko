// The conversation outline: the prompts you sent, listed as anchors back into the pane's
// scrollback. Rules only — ./terminal owns the anchors and ./inspectorview draws the rows.
// In memory only, like a tool payload: a prompt is conversation and never reaches storage.

import type { Prompt, Relay } from "./types";

export interface OutlinePrefs {
  enabled: boolean;
  // Rendered lines a folded row shows. The fold is CSS line-clamp, so a wrapped one-liner
  // and a five-line prompt cost the same height, which is what the rail's width needs.
  lines: number;
  hover: boolean; // resting on a row unfolds it
}

export const OUTLINE_DEFAULTS: OutlinePrefs = { enabled: true, lines: 3, hover: true };
export const OUTLINE_LINES = [1, 2, 3, 5];
export const OUTLINE_SHOW = 6; // rows before the list folds; the rest are one click away

export function clampOutlinePrefs(p: Partial<OutlinePrefs> | null | undefined): OutlinePrefs {
  const lines = Number(p?.lines);
  return {
    enabled: p?.enabled !== false,
    lines: OUTLINE_LINES.includes(lines) ? lines : OUTLINE_DEFAULTS.lines,
    hover: p?.hover !== false,
  };
}

// A memory bound, not a display one: a pane's scrollback runs out long before this, and a
// row whose anchor has gone is still worth reading.
export const PROMPT_CAP = 200;
const TEXT_CAP = 4000; // as ./toolio caps a payload, and for the same reason

export function cleanPrompt(raw: unknown): string {
  if (typeof raw !== "string") return "";
  const t = raw.replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n").trim();
  return t.length > TEXT_CAP ? t.slice(0, TEXT_CAP) + "…" : t;
}

/** The single line a tooltip or a folded row falls back to. */
export function promptLabel(text: string): string {
  const first = text.split("\n").find((l) => l.trim()) ?? "";
  return first.length > 120 ? first.slice(0, 120) + "…" : first;
}

// Turns Claude submits as `user` that nobody typed: a slash command's echo, a `!` shell line,
// an image's sidecar, the notification a background task finished. `UserPromptSubmit` fires for
// these as if you had pressed Enter, so both paths drop them — and only at the START of a
// message, since a `<system-reminder>` pasted INTO a real question leaves it a real question.
const ENVELOPES = [
  "<command-name>", "<command-message>", "<command-args>", "<local-command-stdout>",
  "<local-command-caveat>", "<system-reminder>", "<task-notification>",
  "<bash-input>", "<bash-stdout>", "<bash-stderr>",
  "Caveat: The messages below were generated by the user", "[Request interrupted by user",
  "[Image: ", // what a pasted image files beside the question; `[Image #1] …` IS the question
];
export const isEnvelope = (text: string): boolean => ENVELOPES.some((e) => text.startsWith(e));

// A turn another agent submitted. Listed, since the conversation answered it, but as theirs:
// the frame comes off so the row says who sent what. The transcript adds a preamble the hook lacks.
const RELAY_HEAD = /^(?:Another Claude session sent a message[^:\n]*:\n)?<(agent-message|cross-session-message)\b([^>]*)>\n?/;
const HANDBACK = "[Subagent hand-back]";
const attr = (attrs: string, k: string) => new RegExp(`(?:^|\\s)${k}="([^"]*)"`).exec(attrs)?.[1] ?? "";

export function parseRelay(text: string): { relay: Relay; body: string } | null {
  const m = RELAY_HEAD.exec(text);
  if (!m) return null;
  const kind = m[1] === "agent-message" ? "agent" : "session";
  const from = attr(m[2], "from");
  let body = text.slice(m[0].length).replace(new RegExp(`\\s*</${m[1]}>\\s*$`), "");
  const report = body.startsWith(HANDBACK);
  if (report) { // the harness's warning, then the report indented two columns so it cannot forge a frame
    const at = body.indexOf("\n", body.indexOf("The report follows:"));
    body = (at < 0 ? "" : body.slice(at + 1)).replace(/^ {2}/gm, "");
  }
  const name = attr(m[2], "from-name") || (kind === "agent" ? `agent ${from.slice(0, 7)}` : "another session");
  return { relay: { kind, from, name, report }, body: body.trim() };
}

/** What a list draws for one message: the relay's own words when it is one, else the text as typed. */
export function promptFrom(text: string): { text: string; relay?: Relay } {
  const r = parseRelay(text);
  return r ? { text: r.body || "(empty message)", relay: r.relay } : { text };
}

// The outline's rows, oldest first. Only your questions are numbered, and a run of relays (a
// fan-out's agents reporting back one after another) folds into one row, so they cannot bury them.
export type OutlineItem =
  | { kind: "ask"; p: Prompt; n: number }
  | { kind: "relay"; p: Prompt }
  | { kind: "relays"; id: string; ps: Prompt[] };

export function outlineItems(list: readonly Prompt[]): OutlineItem[] {
  const out: OutlineItem[] = [];
  let n = 0;
  for (let i = 0; i < list.length;) {
    const p = list[i];
    if (!p.relay) { out.push({ kind: "ask", p, n: ++n }); i++; continue; }
    let j = i;
    while (j < list.length && list[j].relay) j++;
    out.push(j - i > 1 ? { kind: "relays", id: p.id, ps: list.slice(i, j) } : { kind: "relay", p });
    i = j;
  }
  return out;
}

let seq = 0;
// Guards a resend of one submit (Codex reports a message twice, started and completed),
// never asking the same thing twice on purpose: a repeat a turn later is its own entry.
const REPEAT_MS = 1500;

/** Returns the entry so the caller can anchor it; null when there is nothing to list. */
export function notePrompt(list: Prompt[], raw: unknown, now: number): Prompt | null {
  const clean = cleanPrompt(raw);
  if (!clean || isEnvelope(clean)) return null;
  const { text, relay } = promptFrom(clean);
  const last = list[list.length - 1];
  if (last && last.text === text && now - last.at < REPEAT_MS) return null;
  const p: Prompt = { id: `p${++seq}`, text, at: now, ...(relay && { relay }) };
  list.push(p);
  if (list.length > PROMPT_CAP) list.splice(0, list.length - PROMPT_CAP);
  return p;
}

// SessionStart fires for all four; only `clear` starts an empty conversation on a cleared
// screen. /compact and /resume carry on, and their prompts are still up in the scrollback.
export const clearsOutline = (source: unknown): boolean => String(source ?? "") === "clear";

// ---------- a resumed pane: the questions are in the transcript, not in its hooks ----------

/** One provider history message, as ./providers hands it over. */
export interface SeedMsg { role: string; text: string; at?: string | null }

/**
 * Everything the transcript holds predates this pane, so restored entries go in front of
 * whatever it has already recorded. Runs once: a second read would list the lot twice, and
 * no dedupe can tell that from a question genuinely asked twice.
 */
export function seedPrompts(list: Prompt[], msgs: readonly SeedMsg[]): Prompt[] {
  if (list.some((p) => p.restored)) return [];
  const restored: Prompt[] = [];
  for (const m of msgs) {
    if (m.role !== "user") continue;
    const clean = cleanPrompt(m.text);
    if (!clean || isEnvelope(clean)) continue;
    const { text, relay } = promptFrom(clean);
    const at = m.at ? Date.parse(m.at) : NaN;
    restored.push({ id: `p${++seq}`, text, at: Number.isFinite(at) ? at : 0, restored: true, ...(relay && { relay }) });
  }
  list.unshift(...restored);
  if (list.length > PROMPT_CAP) list.splice(0, list.length - PROMPT_CAP);
  return restored;
}

// ---------- finding a question in a pane's scrollback ----------
// The address is the text, not a coordinate: the submit hook fires when you press Enter, and
// the REPL commits the line afterwards, above where the cursor then was (docs/sessions.md).

/** A terminal row, read as prose: the REPL's own `>` marker is not part of the question. */
export const normLine = (raw: string): string =>
  raw.replace(/\s+/g, " ").replace(/^[\s>│┃|]+/, "").trim();

export interface PromptKey { key: string; strict: boolean }
const KEY_MAX = 60; // enough to be this question rather than a similar one
const KEY_SHORT = 24; // the retry, for a REPL that wrapped the message narrower than KEY_MAX
const KEY_MIN = 12; // under this an `includes` is a coin toss, so the row must START with the key

const asKey = (key: string): PromptKey => ({ key, strict: key.length < KEY_MIN });

/** What to look for, longest first: a row the REPL wrapped itself holds only the start of it. */
export function promptKeys(text: string): PromptKey[] {
  const first = (text.split("\n").map(normLine).find(Boolean) ?? "").slice(0, KEY_MAX);
  if (!first) return [];
  return first.length > KEY_SHORT ? [asKey(first), asKey(first.slice(0, KEY_SHORT))] : [asKey(first)];
}

export const lineHasPrompt = (line: string, k: PromptKey): boolean =>
  k.strict ? line.startsWith(k.key) : line.includes(k.key);

// How far a screen moved between two readings, in rows: positive when content moved DOWN (a
// page back), negative when it moved UP (a page forward), 0 when nothing did — the far end —
// and null when too little lines up to say. Both directions, or the rows that never move
// (separators, composer, footer) outvote a page forward and read as the far end (that shipped).
const ANCHORS = 4; // matching rows before a shift is a reading rather than a coincidence

export function screenShift(before: readonly string[], after: readonly string[]): number | null {
  let best = 0, bestAt: number | null = null;
  for (let d = 1 - before.length; d < after.length; d++) {
    let n = 0;
    for (let i = Math.max(0, -d); i < before.length && i + d < after.length; i++) {
      if (before[i].trim() && before[i] === after[i + d]) n++;
    }
    if (n > best) { best = n; bestAt = d; }
  }
  return best >= ANCHORS ? bestAt : null;
}

/**
 * Which end to page in from: the live end, unless this list starts where the conversation does
 * (a fresh pane always; a resumed one once the seed has restored what came before) — and then
 * the question's own clock, since rows pile up with time, not with questions (docs/sessions.md).
 */
export function huntFromTop(list: readonly Prompt[], p: Prompt, now: number, resumed: boolean): boolean {
  const start = list[0];
  if (resumed && !start?.restored) return false; // this list begins after the conversation did
  if (!p.at || !start?.at) return list.indexOf(p) < list.length / 2; // no clock to measure with
  return p.at - start.at < now - p.at;
}
